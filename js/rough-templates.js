export function templateRowCount(workType) {
  return (T[workType] || []).length;
}

// ひな形 → 概算の項目の配列。
// 金額が入っているものは確定、0 のものは単価待ちで入る。
export function templateItems(workType) {
  const rows = T[workType];
  if (!rows) return [];
  let order = 0;
  return rows.map((r) => {
    const [name, kind] = r;
    const base = { name, kind, source: 'template', order: order++ };

    if (kind === '労務') {
      // 人工はたたき台。現場が ±ボタンで直す前提なので、はじめから金額を出す
      return { ...base, trade: r[2], persons: r[3], hours: r[4], state: '確定', chosen: 'yotsuba' };
    }
    if (kind === '移動') {
      // 距離は現場ごとに違うので空。人数・時間だけ置いておく
      return { ...base, persons: r[2], hours: r[3], km: null, state: '確定', chosen: 'yotsuba' };
    }
    // 材料・外注。金額が分からないものは 0 で置かず、単価待ちにする
    const amount = r[2];
    if (!amount) return { ...base, state: '単価待ち', chosen: null };
    if (kind === '外注') return { ...base, amount, state: '確定', chosen: 'yotsuba' };
    // 運搬費のような決め打ちの金額は、原価に割り戻さず そのままの金額で入れる
    // （材料15%を乗せる相手ではない）。source:'template' でひな形由来と分かる
    return { ...base, manualAmount: amount, state: '確定', chosen: 'manual' };
  });
}
